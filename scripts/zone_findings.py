"""Summarise the blind-test journal (journal/blind.db) into reports/zone_findings.md.

Tests written by scripts/zone_research.py are "dev" (2023-01..2024-12), "val" (2025-01..2025-07),
"hold" (2025-08..2026-10) and "*_costx" (same, with $ costs scaled by price). Older tests from the
local session (HF data, "hist_*", "oct2026*") are summarised separately.

  .venv/bin/python scripts/zone_findings.py [--final v18_v09_h4only]
"""
from __future__ import annotations

import argparse
import json
import sqlite3
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def stats(g: pd.DataFrame) -> pd.Series:
    w = g.r > 0
    gl = -g.loc[~w, "r"].sum()
    return pd.Series({"trades": len(g), "win_rate": round(w.mean(), 2), "avg_r": round(g.r.mean(), 3),
                      "pf": round(g.loc[w, "r"].sum() / gl, 2) if gl > 0 else np.nan, "total_r": round(g.r.sum(), 1)})


def load() -> pd.DataFrame:
    con = sqlite3.connect(ROOT / "journal" / "blind.db")
    t = pd.read_sql_query("SELECT * FROM blind_trades", con)
    ctx = pd.json_normalize(t["ctx"].fillna("{}").map(json.loads)) if "ctx" in t else pd.DataFrame(index=t.index)
    t = pd.concat([t, ctx], axis=1)
    lv = t.level.fillna("").str.split()
    t["tf"] = lv.str[0]
    t["kind"] = lv.str[1].fillna("").str.replace(r"\d", "", regex=True)
    t["year"] = pd.to_datetime(t.entry_time, utc=True).dt.year
    t["month"] = pd.to_datetime(t.entry_time, utc=True).dt.strftime("%Y-%m")
    t["direction"] = t.side.map({1: "long", -1: "short"})
    if "hour" in t:
        t["entry_hours"] = pd.cut(t["hour"], [-1, 9, 11, 14, 17, 24], labels=["07-09", "10-11", "12-14", "15-17", "18+"])
    if "sl_atr" in t:
        t["stop_atr"] = pd.cut(t["sl_atr"], [0, 1.3, 2.0, 3.0, 9], labels=["<=1.3", "1.3-2", "2-3", ">3"])
    return t


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--final", default="v18_v09_h4only")
    a = ap.parse_args()
    t = load()
    new = t[t.test.isin(["dev", "val", "hold", "dev_costx", "val_costx", "hold_costx"])]
    old = t[~t.index.isin(new.index)]
    out = ["# Zone analyser findings", "",
           "Generated by `scripts/zone_findings.py` from `journal/blind.db`. R after costs (goldbot/costs.py).",
           "DEV = 2023-01..2024-12 (tuning), VAL = 2025-01..2025-07, HOLD = 2025-08..2026-10 (recent, held out).",
           "Data: Twelve Data XAU/USD 15m spot (see docs/knowledge_base.md).", ""]
    v = new.groupby(["variant", "test"]).apply(stats)
    piv = v[["trades", "avg_r", "pf"]].unstack("test")
    piv.columns = [f"{b}_{a_}" for a_, b in piv.columns]
    order = [c for s in ["dev", "val", "hold", "hold_costx"] for c in (f"{s}_trades", f"{s}_avg_r", f"{s}_pf") if c in piv]
    out += ["## Every version by split", "", piv[order].to_string(), ""]
    f = new[new.variant == a.final]
    if len(f):
        out += [f"## Final version `{a.final}`", ""]
        out += ["### by split", "", f.groupby("test").apply(stats).to_string(), ""]
        for col in ["year", "direction", "tf", "kind", "entry_hours", "stop_atr", "reason", "candle"]:
            if col in f and f[col].notna().any():
                x = f.groupby(["test", col], observed=True).apply(stats)
                out += [f"### by {col}", "", x.to_string(), ""]
        h = f[f.test == "hold"]
        if len(h):
            out += ["### holdout by month", "", h.groupby("month").apply(stats).to_string(), ""]
    if len(old):
        old = old.assign(period=np.where(old.test.str.startswith("hist"), "2023-01..2025-07 (HF data)", "Oct 2026 (yfinance proxy)"))
        x = old.groupby(["variant", "period"]).apply(stats).unstack("period")
        out += ["## Local-session runs (older data sources, kept for reference)", "", x.to_string(), ""]
    (ROOT / "reports" / "zone_findings.md").write_text("\n".join(out))
    print("\n".join(out[:12 + len(piv)]))


if __name__ == "__main__":
    main()
